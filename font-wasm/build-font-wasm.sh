#!/usr/bin/env bash
# build-font-wasm.sh -- build fontwrap (lossless font container conversions: WOFF 1.0, WOFF 2.0, EOT) to WebAssembly.
# Plan: fontconverter-web docs/audits/P1-FONTWRAP-PLAN-2026-11-17.md. Licences: own code; Brotli and woff2 MIT;
# libeot MPL-2.0; zlib (Emscripten port) Zlib. Vendored sources and pins: VENDORING.md.
#
# Synchronous callMain, MEMFS/WORKERFS/NODEFS, no Asyncify, no EZYZIPFS, no pthreads, no SIMD, no closure, no
# EXPORT_ES6, no SINGLE_FILE, no WASMFS. Incremental (ninja). Nothing is deleted: every link goes to a fresh staging
# folder, the glue is checked there, and only then is the .js/.wasm pair copied over $OUT_DIR.
#
#   bash font-wasm/build-font-wasm.sh
#   BUILD_DIR=<dir> OUT_DIR=<dir> bash font-wasm/build-font-wasm.sh     (a clean build somewhere else)
#
# Tests: node test-nodefs-contract.js font-wasm/output/fontwrap.js <dir>; node --no-maglev font-wasm/test/test-font-node.js
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
V="$HERE/vendor"
BUILD="${BUILD_DIR:-$HERE/build/wasm}"
OUT="${OUT_DIR:-$HERE/output}"
EMSDK_DIR="${EMSDK:?Set EMSDK to an emsdk checkout with Emscripten 6.0.2 (source its emsdk_env.sh)}"
EMSCRIPTEN_WANTED="6.0.2"

if ! command -v emcc >/dev/null 2>&1; then
  set +u
  # shellcheck disable=SC1091
  source "$EMSDK_DIR/emsdk_env.sh" >/dev/null 2>&1
  set -u
fi
if ! command -v emcc >/dev/null 2>&1; then
  echo "Error: emcc not found. Run: source \"\$EMSDK/emsdk_env.sh\"" >&2
  exit 1
fi
EMVER="$(emcc --version | head -1)"
case "$EMVER" in
  *" $EMSCRIPTEN_WANTED "*) ;;
  *) echo "Error: Emscripten $EMSCRIPTEN_WANTED required, found: $EMVER" >&2; exit 1 ;;
esac
if [ -n "${EM_CACHE:-}" ]; then
  # A private cache the caller made (the published source's build-all.sh, with the zlib port seeded): system
  # libraries and zlib are built into it, never into the emsdk folder.
  echo "Emscripten cache: $EM_CACHE (private)"
else
  export EM_FROZEN_CACHE=1  # never write into the emsdk folder (the zlib port and system libraries are built there)
fi
echo "Emscripten: $EMVER"

# ---- explicit source lists (no globs over vendored trees) ----
BROTLI_SRC="
common/constants.c common/context.c common/dictionary.c common/platform.c common/shared_dictionary.c
common/transform.c
dec/bit_reader.c dec/decode.c dec/huffman.c dec/prefix.c dec/state.c dec/static_init.c
enc/backward_references.c enc/backward_references_hq.c enc/bit_cost.c enc/block_splitter.c enc/brotli_bit_stream.c
enc/cluster.c enc/command.c enc/compound_dictionary.c enc/compress_fragment.c enc/compress_fragment_two_pass.c
enc/dictionary_hash.c enc/encode.c enc/encoder_dict.c enc/entropy_encode.c enc/fast_log.c enc/histogram.c
enc/literal_cost.c enc/memory.c enc/metablock.c enc/static_dict.c enc/static_dict_lut.c enc/static_init.c
enc/utf8_util.c"
WOFF2_SRC="
table_tags.cc variable_length.cc woff2_common.cc woff2_dec.cc woff2_out.cc font.cc glyph.cc normalize.cc
transform.cc woff2_enc.cc"
LIBEOT_SRC="
libeot.c EOT.c writeFontFile.c triplet_encodings.c ctf/parseCTF.c ctf/parseTTF.c ctf/SFNTContainer.c util/stream.c
lzcomp/ahuff.c lzcomp/bitio.c lzcomp/liblzcomp.c lzcomp/lzcomp.c lzcomp/mtxmem.c"
OWN_CXX_SRC="main.cc sfnt.cc info.cc woff1.cc woff2_wrap.cc eot.cc"
OWN_C_SRC="selftest_assert.c"

# ---- flags ----
# House rules: -fexceptions at compile AND link with DISABLE_EXCEPTION_CATCHING=0; libeot reports errors with
# setjmp/longjmp, so SUPPORT_LONGJMP at compile and link; no absolute path reaches the binary.
PREFIX_MAP="-ffile-prefix-map=$HERE=font-wasm"
COMMON="-O2 -fexceptions -sSUPPORT_LONGJMP=1 $PREFIX_MAP"
BROTLI_FLAGS="$COMMON -I$V/brotli/c/include -DBROTLI_STATIC_INIT=1"
WOFF2_FLAGS="$COMMON -std=c++11 -I$V/woff2/include -I$V/woff2/src -I$V/brotli/c/include"
LIBEOT_FLAGS="$COMMON -std=c99 -DDECOMPRESS_ON -I$V/libeot/inc"
OWN_CXX_FLAGS="$COMMON -std=c++17 -Wall -Wextra -Werror -sUSE_ZLIB=1 -I$HERE/src -I$V/woff2/include -I$V/libeot/inc"
OWN_C_FLAGS="$COMMON -std=c99 -Wall -Wextra -Werror"
LDFLAGS="-O2 -fexceptions -sDISABLE_EXCEPTION_CATCHING=0 -sSUPPORT_LONGJMP=1 -sUSE_ZLIB=1 -sWASM=1 \
-sMODULARIZE=1 -sEXPORT_NAME=FontWrap -sENVIRONMENT=web,webview,worker,node \
-sEXPORTED_FUNCTIONS=_main,_malloc,_free \
-sEXPORTED_RUNTIME_METHODS=FS,WORKERFS,NODEFS,callMain,getExceptionMessage,HEAPU8 \
-sINITIAL_MEMORY=67108864 -sMAXIMUM_MEMORY=1073741824 -sABORTING_MALLOC=1 -sALLOW_MEMORY_GROWTH=1 -sGROWABLE_ARRAYBUFFERS=0 \
-sSTACK_SIZE=8388608 -sFILESYSTEM=1 -sFORCE_FILESYSTEM=1 -sEXIT_RUNTIME=0 -sINVOKE_RUN=0 -sASSERTIONS=0 \
-lworkerfs.js -lnodefs.js --post-js $HERE/post.js"

mkdir -p "$BUILD/obj" "$OUT"
STAGE="$BUILD/stage-$(date +%Y%m%d%H%M%S)-$$"
mkdir -p "$STAGE"

# ---- build.ninja ----
NINJA="$BUILD/build.ninja"
OBJS=""
{
  echo "# generated by build-font-wasm.sh -- do not edit"
  echo "rule cc"
  echo "  command = emcc \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule cxx"
  echo "  command = em++ \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule link"
  echo "  command = em++ \$in -o \$out \$ldflags"
  for f in $BROTLI_SRC; do
    o="$BUILD/obj/brotli/${f%.c}.o"; OBJS="$OBJS $o"
    echo "build $o: cc $V/brotli/c/$f"; echo "  flags = $BROTLI_FLAGS"
  done
  for f in $WOFF2_SRC; do
    o="$BUILD/obj/woff2/${f%.cc}.o"; OBJS="$OBJS $o"
    echo "build $o: cxx $V/woff2/src/$f"; echo "  flags = $WOFF2_FLAGS"
  done
  for f in $LIBEOT_SRC; do
    o="$BUILD/obj/libeot/${f%.c}.o"; OBJS="$OBJS $o"
    echo "build $o: cc $V/libeot/src/$f"; echo "  flags = $LIBEOT_FLAGS"
  done
  for f in $OWN_CXX_SRC; do
    o="$BUILD/obj/fontwrap/${f%.cc}.o"; OBJS="$OBJS $o"
    echo "build $o: cxx $HERE/src/$f"; echo "  flags = $OWN_CXX_FLAGS"
  done
  for f in $OWN_C_SRC; do
    o="$BUILD/obj/fontwrap/${f%.c}.o"; OBJS="$OBJS $o"
    echo "build $o: cc $HERE/src/$f"; echo "  flags = $OWN_C_FLAGS"
  done
  echo "build $STAGE/fontwrap.js | $STAGE/fontwrap.wasm: link $OBJS | $HERE/post.js"
  echo "  ldflags = $LDFLAGS"
  echo "default $STAGE/fontwrap.js"
} > "$NINJA.tmp"
mv -f "$NINJA.tmp" "$NINJA"
ninja -j4 -f "$NINJA"

# ---- glue checks, in node (the glue is one very long line; grep is not reliable on it) ----
node -e '
  const s = require("fs").readFileSync(process.argv[1], "latin1");
  const bad = ["toResizableBuffer", "_malloc(arg.length", "currentSafariVersion", "requires Safari", "Asyncify"]
    .filter((b) => s.includes(b));
  if (bad.length) { console.error("FAIL: the glue contains " + bad.join(", ")); process.exit(1); }
  console.log("OK: glue checks");
' "$STAGE/fontwrap.js"

cp -f "$STAGE/fontwrap.js" "$STAGE/fontwrap.wasm" "$OUT/"
rel() {  # flags as used, with no absolute path: the prefix map's own source shows as <font-wasm dir>
  local s="${1//-ffile-prefix-map=$HERE=/-ffile-prefix-map=<font-wasm dir>=}"
  echo "${s//$HERE/font-wasm}"
}
PINS_LINE="$(sed -n 's/^  "\([a-z0-9]*\) *[^ ]* *\([0-9a-f]\{40\}\) .*/\1@\2/p' "$HERE/vendor/fetch-vendor.sh" | tr '\n' ' ')"
PATCHES_LINE="$(cd "$HERE/vendor/patches" && ls -- *.patch | tr '\n' ' ')"
{
  echo "fontwrap build (font-wasm/build-font-wasm.sh)"
  echo "emscripten:    $EMVER"
  echo "pins:          ${PINS_LINE}zlib@1.3.2 (Emscripten port)"
  echo "patches:       $PATCHES_LINE(vendor/patches, applied by vendor/fetch-vendor.sh)"
  echo "brotli flags:  $(rel "$BROTLI_FLAGS")"
  echo "woff2 flags:   $(rel "$WOFF2_FLAGS")"
  echo "libeot flags:  $(rel "$LIBEOT_FLAGS")"
  echo "own C++ flags: $(rel "$OWN_CXX_FLAGS")"
  echo "own C flags:   $(rel "$OWN_C_FLAGS")"
  echo "link flags:    $(rel "$LDFLAGS")"
  echo "sources:       brotli [$BROTLI_SRC ] woff2 [$WOFF2_SRC ] libeot [$LIBEOT_SRC ] own [$OWN_CXX_SRC $OWN_C_SRC ]"
  (cd "$OUT" && shasum -a 256 fontwrap.js fontwrap.wasm)
} > "$OUT/BUILD-INFO.txt"
ls -l "$OUT/fontwrap.js" "$OUT/fontwrap.wasm"
echo "BUILD-OK"
