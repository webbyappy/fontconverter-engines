#!/usr/bin/env bash
# build-native.sh -- the same fontwrap sources built natively with AddressSanitizer and UBSan: the first test layer
# (P1 plan, section 3.6). zlib is compiled from the Emscripten port's own 1.3.2 source, so native and wasm outputs can
# be compared byte for byte (P1-12). Output: build/native/fontwrap-asan (not committed).
#
#   bash font-wasm/build-native.sh
#   FONTWRAP_ENGINE=native:font-wasm/build/native/fontwrap-asan node --no-maglev font-wasm/test/test-font-node.js
#   node font-wasm/test/mutation-sweep.mjs font-wasm/build/native/fontwrap-asan
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
V="$HERE/vendor"
BUILD="${BUILD_DIR:-$HERE/build/native}"
EMSDK_DIR="${EMSDK:?Set EMSDK to an emsdk checkout with Emscripten 6.0.2 (source its emsdk_env.sh)}"
Z="$EMSDK_DIR/upstream/emscripten/cache/ports/zlib/zlib-1.3.2"
if [ ! -f "$Z/zlib.h" ]; then
  echo "Error: the Emscripten zlib port source is not at $Z (P1-12); stop and decide with the owner" >&2
  exit 1
fi

ZLIB_SRC="adler32.c compress.c crc32.c deflate.c infback.c inffast.c inflate.c inftrees.c trees.c uncompr.c zutil.c"
BROTLI_SRC="
common/constants.c common/context.c common/dictionary.c common/platform.c common/shared_dictionary.c
common/transform.c
dec/bit_reader.c dec/decode.c dec/huffman.c dec/prefix.c dec/state.c dec/static_init.c
enc/backward_references.c enc/backward_references_hq.c enc/bit_cost.c enc/block_splitter.c enc/brotli_bit_stream.c
enc/cluster.c enc/command.c enc/compound_dictionary.c enc/compress_fragment.c enc/compress_fragment_two_pass.c
enc/dictionary_hash.c enc/encode.c enc/encoder_dict.c enc/entropy_encode.c enc/fast_log.c enc/histogram.c
enc/literal_cost.c enc/memory.c enc/metablock.c enc/static_dict.c enc/static_dict_lut.c enc/static_init.c
enc/utf8_util.c"
WOFF2_SRC="
table_tags.cc variable_length.cc woff2_common.cc woff2_dec.cc woff2_out.cc font.cc glyph.cc normalize.cc
transform.cc woff2_enc.cc"
LIBEOT_SRC="
libeot.c EOT.c writeFontFile.c triplet_encodings.c ctf/parseCTF.c ctf/parseTTF.c ctf/SFNTContainer.c util/stream.c
lzcomp/ahuff.c lzcomp/bitio.c lzcomp/liblzcomp.c lzcomp/lzcomp.c lzcomp/mtxmem.c"
OWN_CXX_SRC="main.cc sfnt.cc info.cc woff1.cc woff2_wrap.cc eot.cc"
OWN_C_SRC="selftest_assert.c"

# -fexceptions on the C sources too, as in the wasm build: the assert handler throws through libeot's C frames
# (P1-14; the native assertion test, not the flag, is the proof).
SAN="-O1 -g -fno-omit-frame-pointer -fsanitize=address,undefined -fno-sanitize-recover=undefined -fexceptions"
ZLIB_FLAGS="$SAN -I$Z"
BROTLI_FLAGS="$SAN -I$V/brotli/c/include -DBROTLI_STATIC_INIT=1"
WOFF2_FLAGS="$SAN -std=c++11 -I$V/woff2/include -I$V/woff2/src -I$V/brotli/c/include"
LIBEOT_FLAGS="$SAN -std=c99 -DDECOMPRESS_ON -I$V/libeot/inc"
OWN_CXX_FLAGS="$SAN -std=c++17 -Wall -Wextra -Werror -I$HERE/src -I$Z -I$V/woff2/include -I$V/libeot/inc"
OWN_C_FLAGS="$SAN -std=c99 -Wall -Wextra -Werror"

mkdir -p "$BUILD/obj"
NINJA="$BUILD/build.ninja"
OBJS=""
{
  echo "# generated by build-native.sh -- do not edit"
  echo "rule cc"
  echo "  command = clang \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule cxx"
  echo "  command = clang++ \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule link"
  echo "  command = clang++ \$in -o \$out -fsanitize=address,undefined"
  for f in $ZLIB_SRC; do
    o="$BUILD/obj/zlib/${f%.c}.o"; OBJS="$OBJS $o"; echo "build $o: cc $Z/$f"; echo "  flags = $ZLIB_FLAGS"
  done
  for f in $BROTLI_SRC; do
    o="$BUILD/obj/brotli/${f%.c}.o"; OBJS="$OBJS $o"; echo "build $o: cc $V/brotli/c/$f"; echo "  flags = $BROTLI_FLAGS"
  done
  for f in $WOFF2_SRC; do
    o="$BUILD/obj/woff2/${f%.cc}.o"; OBJS="$OBJS $o"; echo "build $o: cxx $V/woff2/src/$f"; echo "  flags = $WOFF2_FLAGS"
  done
  for f in $LIBEOT_SRC; do
    o="$BUILD/obj/libeot/${f%.c}.o"; OBJS="$OBJS $o"; echo "build $o: cc $V/libeot/src/$f"; echo "  flags = $LIBEOT_FLAGS"
  done
  for f in $OWN_CXX_SRC; do
    o="$BUILD/obj/fontwrap/${f%.cc}.o"; OBJS="$OBJS $o"; echo "build $o: cxx $HERE/src/$f"; echo "  flags = $OWN_CXX_FLAGS"
  done
  for f in $OWN_C_SRC; do
    o="$BUILD/obj/fontwrap/${f%.c}.o"; OBJS="$OBJS $o"; echo "build $o: cc $HERE/src/$f"; echo "  flags = $OWN_C_FLAGS"
  done
  echo "build $BUILD/fontwrap-asan: link $OBJS"
  echo "default $BUILD/fontwrap-asan"
} > "$NINJA.tmp"
mv -f "$NINJA.tmp" "$NINJA"
ninja -j4 -f "$NINJA"
ls -l "$BUILD/fontwrap-asan"
echo "NATIVE-BUILD-OK"
