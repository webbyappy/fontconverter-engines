#!/usr/bin/env bash
# build-native.sh -- the same hbfont sources built natively with AddressSanitizer and UBSan: the first test layer
# (fontconverter-web P3b plan, section 4.1). zlib is compiled from the Emscripten port's own 1.3.2 source, so native
# and wasm outputs can be compared byte for byte. Output: build/native/hbfont-asan (not committed).
#
#   bash harfbuzz-wasm/build-native.sh
#   HBFONT_ENGINE=native:harfbuzz-wasm/build/native/hbfont-asan node --no-maglev harfbuzz-wasm/test/test-hbfont-node.js
#   node harfbuzz-wasm/test/mutation-sweep.mjs harfbuzz-wasm/build/native/hbfont-asan
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
V="$HERE/vendor"
BUILD="${BUILD_DIR:-$HERE/build/native}"
EMSDK_DIR="${EMSDK:?Set EMSDK to an emsdk checkout with Emscripten 6.0.2 (source its emsdk_env.sh)}"
Z="$EMSDK_DIR/upstream/emscripten/cache/ports/zlib/zlib-1.3.2"
if [ ! -f "$Z/zlib.h" ]; then
  echo "Error: the Emscripten zlib port source is not at $Z; stop and decide with the owner" >&2
  exit 1
fi

ZLIB_SRC="adler32.c compress.c crc32.c deflate.c infback.c inffast.c inflate.c inftrees.c trees.c uncompr.c zutil.c"
HB_SRC="harfbuzz-subset.cc"
OWN_CXX_SRC="main.cc sfnt.cc names.cc info.cc instance.cc instance_names.cc sfnt_edit.cc cff.cc cff_name.cc cff_namekey.cc svg_table.cc transplant.cc"

SAN="-O1 -g -fno-omit-frame-pointer -fsanitize=address,undefined -fno-sanitize-recover=undefined -fexceptions"
ZLIB_FLAGS="$SAN -I$Z"
HB_FLAGS="$SAN -std=c++11 -DNDEBUG -DHB_NO_MT -I$V/harfbuzz/src"
OWN_CXX_FLAGS="$SAN -std=c++17 -Wall -Wextra -Werror -DHB_NO_MT -I$HERE/src -I$Z -I$V/harfbuzz/src"

mkdir -p "$BUILD/obj"
NINJA="$BUILD/build.ninja"
OBJS=""
{
  echo "# generated by build-native.sh -- do not edit"
  echo "rule cc"
  echo "  command = clang \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule cxx"
  echo "  command = clang++ \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule link"
  echo "  command = clang++ \$in -o \$out -fsanitize=address,undefined"
  for f in $ZLIB_SRC; do
    o="$BUILD/obj/zlib/${f%.c}.o"; OBJS="$OBJS $o"; echo "build $o: cc $Z/$f"; echo "  flags = $ZLIB_FLAGS"
  done
  for f in $HB_SRC; do
    o="$BUILD/obj/harfbuzz/${f%.cc}.o"; OBJS="$OBJS $o"; echo "build $o: cxx $V/harfbuzz/src/$f"
    echo "  flags = $HB_FLAGS"
  done
  for f in $OWN_CXX_SRC; do
    o="$BUILD/obj/hbfont/${f%.cc}.o"; OBJS="$OBJS $o"; echo "build $o: cxx $HERE/src/$f"; echo "  flags = $OWN_CXX_FLAGS"
  done
  echo "build $BUILD/hbfont-asan: link $OBJS"
  echo "default $BUILD/hbfont-asan"
} > "$NINJA.tmp"
mv -f "$NINJA.tmp" "$NINJA"
ninja -j2 -f "$NINJA"
ls -l "$BUILD/hbfont-asan"
echo "NATIVE-BUILD-OK"
