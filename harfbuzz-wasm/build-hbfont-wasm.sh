#!/usr/bin/env bash
# build-hbfont-wasm.sh -- build hbfont (HarfBuzz 15.0.0's instancer and subsetter as a command line) to WebAssembly.
# Plan: fontconverter-web docs/audits/P3b-VARIABLE-COLOUR-PLAN-2026-11-18.md, section 3.1. Licences: own code;
# HarfBuzz MIT ("Old MIT"); zlib (Emscripten port) Zlib. Vendored sources and pin: VENDORING.md.
#
# Synchronous callMain, MEMFS/WORKERFS/NODEFS, no Asyncify, no pthreads, no SIMD, no closure, no EXPORT_ES6, no
# SINGLE_FILE, no WASMFS. Linked with a 1 GiB ceiling that aborts on allocation failure (P3b-5). Incremental (ninja).
# Nothing is deleted: every link goes to a fresh staging folder, the glue is checked there, and only then is the
# .js/.wasm pair copied over $OUT_DIR.
#
#   bash harfbuzz-wasm/build-hbfont-wasm.sh
#   BUILD_DIR=<dir> OUT_DIR=<dir> bash harfbuzz-wasm/build-hbfont-wasm.sh     (a clean build somewhere else)
#
# Tests: node test-nodefs-contract.js harfbuzz-wasm/output/hbfont.js <dir>;
#        node --no-maglev harfbuzz-wasm/test/test-hbfont-node.js
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
V="$HERE/vendor"
BUILD="${BUILD_DIR:-$HERE/build/wasm}"
OUT="${OUT_DIR:-$HERE/output}"
EMSDK_DIR="${EMSDK:?Set EMSDK to an emsdk checkout with Emscripten 6.0.2 (source its emsdk_env.sh)}"
EMSCRIPTEN_WANTED="6.0.2"

if ! command -v emcc >/dev/null 2>&1; then
  set +u
  # shellcheck disable=SC1091
  source "$EMSDK_DIR/emsdk_env.sh" >/dev/null 2>&1
  set -u
fi
if ! command -v emcc >/dev/null 2>&1; then
  echo "Error: emcc not found. Run: source \"\$EMSDK/emsdk_env.sh\"" >&2
  exit 1
fi
EMVER="$(emcc --version | head -1)"
case "$EMVER" in
  *" $EMSCRIPTEN_WANTED "*) ;;
  *) echo "Error: Emscripten $EMSCRIPTEN_WANTED required, found: $EMVER" >&2; exit 1 ;;
esac
if [ -n "${EM_CACHE:-}" ]; then
  # A private cache the caller made (the published source's build-all.sh, with the zlib port seeded): system
  # libraries and zlib are built into it, never into the emsdk folder.
  echo "Emscripten cache: $EM_CACHE (private)"
else
  export EM_FROZEN_CACHE=1  # never write into the emsdk folder (the zlib port and system libraries are built there)
fi
echo "Emscripten: $EMVER"

# ---- explicit source lists (no globs over vendored trees) ----
HB_SRC="harfbuzz-subset.cc"  # HarfBuzz's own amalgamation: the core, shaping and hb-subset in one unit
OWN_CXX_SRC="main.cc sfnt.cc names.cc info.cc instance.cc instance_names.cc sfnt_edit.cc cff.cc cff_name.cc cff_namekey.cc svg_table.cc transplant.cc"

# ---- flags ----
# HarfBuzz as its release builds compile it (C++11, NDEBUG), single-threaded (HB_NO_MT: no pthreads here), with
# -fexceptions so own code's exceptions may pass through its frames (house rule: at compile AND link, with
# DISABLE_EXCEPTION_CATCHING=0). No absolute path reaches the binary.
PREFIX_MAP="-ffile-prefix-map=$HERE=harfbuzz-wasm"
COMMON="-O2 -fexceptions $PREFIX_MAP"
HB_FLAGS="$COMMON -std=c++11 -DNDEBUG -DHB_NO_MT -I$V/harfbuzz/src"
OWN_CXX_FLAGS="$COMMON -std=c++17 -Wall -Wextra -Werror -sUSE_ZLIB=1 -DHB_NO_MT -I$HERE/src -I$V/harfbuzz/src"
LDFLAGS="-O2 -fexceptions -sDISABLE_EXCEPTION_CATCHING=0 -sUSE_ZLIB=1 -sWASM=1 \
-sMODULARIZE=1 -sEXPORT_NAME=HBFont -sENVIRONMENT=web,webview,worker,node \
-sEXPORTED_FUNCTIONS=_main,_malloc,_free \
-sEXPORTED_RUNTIME_METHODS=FS,WORKERFS,NODEFS,callMain,getExceptionMessage,HEAPU8 \
-sINITIAL_MEMORY=67108864 -sMAXIMUM_MEMORY=1073741824 -sABORTING_MALLOC=1 -sALLOW_MEMORY_GROWTH=1 -sGROWABLE_ARRAYBUFFERS=0 \
-sSTACK_SIZE=8388608 -sFILESYSTEM=1 -sFORCE_FILESYSTEM=1 -sEXIT_RUNTIME=0 -sINVOKE_RUN=0 -sASSERTIONS=0 \
-lworkerfs.js -lnodefs.js --post-js $HERE/post.js"

mkdir -p "$BUILD/obj" "$OUT"
STAGE="$BUILD/stage-$(date +%Y%m%d%H%M%S)-$$"
mkdir -p "$STAGE"

# ---- build.ninja ----
NINJA="$BUILD/build.ninja"
OBJS=""
{
  echo "# generated by build-hbfont-wasm.sh -- do not edit"
  echo "rule cxx"
  echo "  command = em++ \$flags -MD -MF \$out.d -c \$in -o \$out"
  echo "  depfile = \$out.d"
  echo "  deps = gcc"
  echo "rule link"
  echo "  command = em++ \$in -o \$out \$ldflags"
  for f in $HB_SRC; do
    o="$BUILD/obj/harfbuzz/${f%.cc}.o"; OBJS="$OBJS $o"
    echo "build $o: cxx $V/harfbuzz/src/$f"; echo "  flags = $HB_FLAGS"
  done
  for f in $OWN_CXX_SRC; do
    o="$BUILD/obj/hbfont/${f%.cc}.o"; OBJS="$OBJS $o"
    echo "build $o: cxx $HERE/src/$f"; echo "  flags = $OWN_CXX_FLAGS"
  done
  echo "build $STAGE/hbfont.js | $STAGE/hbfont.wasm: link $OBJS | $HERE/post.js"
  echo "  ldflags = $LDFLAGS"
  echo "default $STAGE/hbfont.js"
} > "$NINJA.tmp"
mv -f "$NINJA.tmp" "$NINJA"
ninja -j2 -f "$NINJA"

# ---- glue checks, in node (the glue is one very long line; grep is not reliable on it) ----
node -e '
  const s = require("fs").readFileSync(process.argv[1], "latin1");
  const bad = ["toResizableBuffer", "_malloc(arg.length", "currentSafariVersion", "requires Safari", "Asyncify"]
    .filter((b) => s.includes(b));
  if (bad.length) { console.error("FAIL: the glue contains " + bad.join(", ")); process.exit(1); }
  console.log("OK: glue checks");
' "$STAGE/hbfont.js"

cp -f "$STAGE/hbfont.js" "$STAGE/hbfont.wasm" "$OUT/"
rel() {  # flags as used, with no absolute path: the prefix map's own source shows as <harfbuzz-wasm dir>
  local s="${1//-ffile-prefix-map=$HERE=/-ffile-prefix-map=<harfbuzz-wasm dir>=}"
  echo "${s//$HERE/harfbuzz-wasm}"
}
HB_SHA="$(sed -n 's/^WANT=\([0-9a-f]\{64\}\)$/\1/p' "$HERE/vendor/fetch-vendor.sh")"
PATCHES_LINE="$(cd "$HERE/vendor" && { ls -- patches/*.patch 2>/dev/null || echo none; } | tr '\n' ' ')"
{
  echo "hbfont build (harfbuzz-wasm/build-hbfont-wasm.sh)"
  echo "emscripten:    $EMVER"
  echo "pins:          harfbuzz@15.0.0 (release tarball sha256 $HB_SHA) zlib@1.3.2 (Emscripten port)"
  echo "patches:       $PATCHES_LINE(vendor/patches, applied by vendor/fetch-vendor.sh)"
  echo "harfbuzz flags: $(rel "$HB_FLAGS")"
  echo "own C++ flags: $(rel "$OWN_CXX_FLAGS")"
  echo "link flags:    $(rel "$LDFLAGS")"
  echo "sources:       harfbuzz [$HB_SRC ] own [$OWN_CXX_SRC ]"
  (cd "$OUT" && shasum -a 256 hbfont.js hbfont.wasm)
} > "$OUT/BUILD-INFO.txt"
ls -l "$OUT/hbfont.js" "$OUT/hbfont.wasm"
echo "BUILD-OK"
